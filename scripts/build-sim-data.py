#!/usr/bin/env python3
"""Build the simulator roster from the published character catalog and dossiers."""

from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
STAT_NAMES = ("Durability", "Energy", "Intelligence", "Psionics", "Speed", "Strength")


class CatalogParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.characters = []
        self.in_main = False
        self.in_card = False
        self.in_heading = False
        self.depth = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "main":
            self.in_main = True
        if self.in_main and tag == "div":
            if self.in_card:
                self.depth += 1
            elif "character" in attrs.get("class", "").split():
                self.in_card = True
                self.depth = 1
                self.card = {"name": "", "image": "", "profile": ""}
        if self.in_card and tag == "a" and not self.card["profile"]:
            self.card["profile"] = attrs.get("href", "")
        if self.in_card and tag == "img" and not self.card["image"]:
            self.card["image"] = attrs.get("src", "")
        if self.in_card and tag == "h2":
            self.in_heading = True

    def handle_data(self, data):
        if self.in_heading:
            self.card["name"] += data

    def handle_endtag(self, tag):
        if tag == "h2":
            self.in_heading = False
        if tag == "div" and self.in_card:
            self.depth -= 1
            if self.depth == 0:
                self.card["name"] = unescape(self.card["name"].strip())
                self.characters.append(self.card)
                self.in_card = False
        if tag == "main":
            self.in_main = False


def dossier_stats(profile):
    source = (ROOT / profile).read_text()
    readings = re.search(r'<div class="scanner-readings">(.*?)</div>\s*</section>', source, re.S)
    if not readings:
        return None
    meters = re.findall(r'<div class="scanner-meter"[^>]*data-base="(\d+)"', readings.group(1))
    if len(meters) != len(STAT_NAMES):
        return None
    values = [int(value) for value in meters]
    return values if any(values) else None


def main():
    parser = CatalogParser()
    parser.feed((ROOT / "characters.html").read_text())
    roster = []
    for card in parser.characters:
        if not card["profile"].startswith("characters/"):
            raise ValueError(f"Missing profile for {card['name']}")
        card["stats"] = dossier_stats(card["profile"])
        roster.append(card)
    output = "// Generated by scripts/build-sim-data.py from characters.html and character dossiers.\n"
    output += "window.simCharacters = " + json.dumps(roster, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "js" / "sim-data.js").write_text(output)
    print(f"Built {len(roster)} characters ({sum(card['stats'] is not None for card in roster)} with ratings).")


if __name__ == "__main__":
    main()
