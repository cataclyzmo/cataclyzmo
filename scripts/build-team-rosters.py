"""Copy published character dossier data into the static team carousel bundle.

Run from the repository root after changing a member's character profile.
"""

from html import unescape
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
ROSTERS = {
    "cataclyzmo": [("Century", "the-yesterday-man"), ("A.I.", "ai"), ("Nightmare", "nightmare"), ("Dark Matter", "dark-matter"), ("Metamorphosis", "metamorphosis")],
    "scavengers": [("Commander Rex", "commandrex"), ("Element-9", "element-9"), ("Unity", "unity"), ("11:05", "11-05"), ("Teller", "teller"), ("Demon", "demon")],
    "society": [("Bandit", "bandit"), ("Quick Draw", "quickdraw"), ("Gunslinger", "gunslinger"), ("Tallahassee & Redback", "tallahassee-redback")],
    "humanoids": [("Queen Bee", "queen-bee"), ("Night Howl", "night-howl"), ("Man Tiger", "man-tiger"), ("Barracuda", "barracuda"), ("Komodo", "komodo")],
    "force-five": [("Shadow Drone", "shadow-drone"), ("The Ultimatum", "the-ultimatum"), ("Kid Quickster", "kid-quickster"), ("Invisible Mistress", "invisible-mistress"), ("Phase-Out", "phase-out")],
    "hero": [("Super Seven", "super-seven"), ("All-American", "all-american"), ("Kid Justice", "kid-justice"), ("The Shadower", "the-shadower"), ("Night-Hawk", "night-hawk"), ("Valkyrie", "valkyrie"), ("Vigilante-X", "vigilante-x")],
    "iga": [("The Other", "other"), ("Deathmonger", "deathmonger"), ("Cold Fusion", "cold-fusion"), ("Black Matter", "black-matter"), ("Meta", "meta")],
}

def clean(value):
    return " ".join(unescape(re.sub(r"<[^>]+>", "", value)).split())


def profile(slug):
    source = (ROOT / "characters" / f"{slug}.html").read_text()
    match = re.search(r"<aside\b[^>]*>(.*?)</aside>", source, re.S)
    if not match:
        raise ValueError(f"Missing aside in {slug}")
    aside = match.group(1)
    portrait = re.search(r"<img\b[^>]*id=\"characterImage\"[^>]*>", aside)
    if not portrait:
        raise ValueError(f"Missing portrait in {slug}")
    image = re.search(r'src="([^"]+)"', portrait.group())[1]
    equipment = re.search(r'data-equipment-portrait="([^"]+)"', aside)
    stats = []
    for block in re.findall(r'<div class="scanner-stat">(.*?)<div class="scanner-meter"([^>]+)>', aside, re.S):
        heading, meter = block
        base = re.search(r'data-base="(\d+)"', meter)
        equipped = re.search(r'data-equipped="(\d+)"', meter)
        if not base or not equipped:
            continue
        base, equipped = int(base[1]), int(equipped[1])
        ratings = re.findall(r'<span class="stat-rating[^"]*">([^<]+)', heading)
        labels = [clean(rating.split('·', 1)[1]) if '·' in rating else '' for rating in ratings]
        if base != equipped:
            if len(labels) != 2:
                raise ValueError(f"Missing base/equipped rating in {slug}")
            stats.append([base, equipped, labels[1], labels[0]])
        else:
            stats.append([base, equipped, labels[0] if labels else ''])
    if len(stats) != 6 or all(base == equipped == 0 and not label for base, equipped, label, *rest in stats):
        stats = None
    facts = {}
    for label, value in re.findall(r'<tr>\s*<td>(.*?)</td>\s*<td>(.*?)</td>\s*</tr>', aside, re.S):
        facts[clean(label)] = clean(value)
    result = {"image": image, "stats": stats, "facts": facts, "profile": f"../characters/{slug}.html"}
    if equipment:
        result["equipmentImage"] = equipment[1]
    return result


def main():
    rosters = {}
    for team, members in ROSTERS.items():
        roster = []
        for name, slug in members:
            member = {"name": name, **profile(slug)}
            roster.append(member)
        rosters[team] = roster
    output = "// Generated by scripts/build-team-rosters.py from the character profiles.\n"
    output += "window.teamRosters = " + json.dumps(rosters, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "js" / "team-rosters.js").write_text(output)


if __name__ == "__main__":
    main()
