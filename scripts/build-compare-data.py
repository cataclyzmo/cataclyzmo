#!/usr/bin/env python3
"""Build comparison cards from the published character catalog and dossiers."""

from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


class CatalogParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.characters = []
        self.in_main = False
        self.in_card = False
        self.in_heading = False
        self.depth = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "main":
            self.in_main = True
        if self.in_main and tag == "div":
            if self.in_card:
                self.depth += 1
            elif "character" in attrs.get("class", "").split():
                self.in_card = True
                self.depth = 1
                self.card = {"name": "", "image": "", "profile": ""}
        if self.in_card and tag == "a" and not self.card["profile"]:
            self.card["profile"] = attrs.get("href", "")
        if self.in_card and tag == "img" and not self.card["image"]:
            self.card["image"] = attrs.get("src", "")
        if self.in_card and tag == "h2":
            self.in_heading = True

    def handle_data(self, data):
        if self.in_heading:
            self.card["name"] += data

    def handle_endtag(self, tag):
        if tag == "h2":
            self.in_heading = False
        if tag == "div" and self.in_card:
            self.depth -= 1
            if self.depth == 0:
                self.card["name"] = unescape(self.card["name"].strip())
                self.characters.append(self.card)
                self.in_card = False
        if tag == "main":
            self.in_main = False


def clean(value):
    return " ".join(unescape(re.sub(r"<[^>]+>", "", value)).split())


def dossier(profile):
    source = (ROOT / profile).read_text()
    aside_match = re.search(r"<aside\b[^>]*>(.*?)</aside>", source, re.S)
    if not aside_match:
        raise ValueError(f"Missing dossier in {profile}")
    aside = aside_match.group(1)
    stats = []
    for heading, meter in re.findall(r'<div class="scanner-stat">(.*?)<div class="scanner-meter"([^>]+)>', aside, re.S):
        base = re.search(r'data-base="(\d+)"', meter)
        potential = re.search(r'data-equipped="(\d+)"', meter)
        if not base or not potential:
            continue
        base, potential = int(base[1]), int(potential[1])
        ratings = re.findall(r'<span class="stat-rating[^"]*">([^<]+)', heading)
        labels = [clean(value.split('·', 1)[1]) if '·' in value else '' for value in ratings]
        if base != potential:
            if len(labels) != 2:
                raise ValueError(f"Missing base or potential rating in {profile}")
            stats.append([base, potential, labels[1], labels[0]])
        else:
            stats.append([base, potential, labels[0] if labels else ''])
    if len(stats) != 6 or all(base == potential == 0 and not label for base, potential, label, *rest in stats):
        stats = None
    facts = {}
    for label, value in re.findall(r'<tr>\s*<td>(.*?)</td>\s*<td>(.*?)</td>\s*</tr>', aside, re.S):
        label, value = clean(label), clean(value)
        if label and value:
            facts[label] = value
    return {"stats": stats, "facts": facts}


def main():
    parser = CatalogParser()
    parser.feed((ROOT / "characters.html").read_text())
    roster = []
    for card in parser.characters:
        if not card["profile"].startswith("characters/") or not (ROOT / card["profile"]).is_file():
            raise ValueError(f"Missing profile for {card['name']}")
        card.update(dossier(card["profile"]))
        roster.append(card)
    output = "// Generated by scripts/build-compare-data.py from characters.html and character dossiers.\n"
    output += "window.compareCharacters = " + json.dumps(roster, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "js" / "compare-data.js").write_text(output)
    print(f"Built {len(roster)} characters ({sum(card['stats'] is not None for card in roster)} with ratings).")


if __name__ == "__main__":
    main()
